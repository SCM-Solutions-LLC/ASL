import React from "react";
import { interpolate, interpolateColors, useCurrentFrame } from "remotion";
import { makeEdit } from "../../edit";
import alignment from "../../generated/cell-count.alignment.json";
import { SANS, SERIF } from "../../fonts";
import { Tag } from "../../scenes/space";
import type { Short } from "../types";
import { Slide } from "./set";

// A short with no cast. The subject is a count, so the frame holds a unit chart in the shape of a
// person: 68 dots, one per trillion cells, and every beat is something happening to those dots.
//
// The voice-over is Kokoro, generated by `npm run tts -- cell-count` from
// script/cell-count.txt, which also carries the sources for every number here. Every beat below
// hangs off a spoken word rather than a frame number, so re-reading the script re-resolves the
// cut instead of breaking it.
const edit = makeEdit({
  alignment,
  keyPhrases: [["less", "than", "half"], ["thirty", "trillion"], ["Thirty-eight", "trillion"], ["two", "hundred", "grams."],
    ["Eighty-four", "percent"], ["mostly", "blood."], ["outnumbered"]],
  // The scale sentence is fifteen words, which is five lines in the 9:16 caption block against
  // the four it has room for; it breaks on its own comma.
  breakAfter: ["scale,"],
});

// Every beat hangs off a spoken word, so a re-read of the script re-resolves the cut.
const F = {
  less: edit.at("less"),
  half: edit.at("half"),
  thirty: edit.at("thirty"),
  thirtyEight: edit.at("Thirty-eight"),
  scale: edit.at("scale,"),
  two: edit.at("two"),
  own: edit.at("own"),
  eightyFour: edit.at("Eighty-four"),
  red: edit.at("red"),
  mostly: edit.at("mostly"),
  outnumbered: edit.at("outnumbered"),
  passengers: edit.at("passengers."),
};

const ramp = (f: number, a: number, b: number, from = 0, to = 1) =>
  interpolate(f, [a, b], [from, to], { extrapolateLeft: "clamp", extrapolateRight: "clamp" });
const smooth = (t: number) => t * t * (3 - 2 * t);

// Deterministic, so a dot is the same kind of cell on every render and every re-render.
const rng = (seed: number) => () => {
  seed = (seed * 1664525 + 1013904223) % 4294967296;
  return seed / 4294967296;
};

// The figure, one character per dot. It is a unit chart before it is a drawing: there are exactly
// 68 X's, one per trillion cells in Sender, Fuchs & Milo's reference man, and the module refuses to
// load if an edit to the picture changes that.
const FIGURE = [
  "...XXX...",
  "...XXX...",
  ".XXXXXXX.",
  "XXXXXXXXX",
  "X.XXXXX.X",
  "X.XXXXX.X",
  "X.XXXXX.X",
  "..XXXXX..",
  "..XX.XX..",
  "..XX.XX..",
  "..XX.XX..",
  "..XX.XX..",
  "..XX.XX..",
];
const HUMAN = 30;
const BACTERIA = 38;
// 2.5e13 red blood cells is 25 dots of the 30. That is 83% on the chart; the label carries the
// paper's 84%, which is the same number before rounding to whole trillions.
const RED = 25;

// Both crops have to hold everything, and the 9:16 window is only 885 stage units wide (x 517–1403),
// so the figure takes the left of that window and the right 350 units are the column the labels and
// the scale live in. Everything sits above y 850, which is where the 16:9 captions start.
const PITCH = 52;
const R = 21;
const ORIGIN = { x: 566, y: 130 };
const COLUMN = 1040;

// The scale's pan, and the mound the bacteria make on it: rows of 11, 10, 9 and 8 is 38.
const PAN = { x: 1215, y: 640, w: 300 };
const MOUND = [11, 10, 9, 8];
const SMALL = 7;
const PILE = MOUND.flatMap((n, row) =>
  Array.from({ length: n }, (_, i) => ({ x: PAN.x + (i - (n - 1) / 2) * 17, y: PAN.y - 8 - row * 13 })),
);

type Dot = {
  x: number;
  y: number;
  human: boolean;
  red: boolean;
  /** Position within its own population, for staggering. */
  n: number;
  angle: number;
  phase: number;
};

const DOTS: Dot[] = (() => {
  const at = FIGURE.flatMap((row, r) => [...row].flatMap((c, col) => (c === "X" ? [{ x: ORIGIN.x + col * PITCH, y: ORIGIN.y + r * PITCH }] : [])));
  if (at.length !== HUMAN + BACTERIA) throw new Error(`The figure has ${at.length} dots; the chart needs ${HUMAN + BACTERIA}`);
  if (PILE.length !== BACTERIA) throw new Error(`The mound holds ${PILE.length}; it needs ${BACTERIA}`);

  // Which dot is which kind is shuffled, not anatomical: this is a count, not a map. Nearly all of
  // the bacteria are really in the colon, and a figure with a green gut would be a different claim.
  const next = rng(5);
  const order = at.map((_, i) => i);
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(next() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  const rank = new Map(order.map((idx, k) => [idx, k]));
  let h = 0;
  let b = 0;
  // Numbered in reading order within each population, so a recolour sweeps down the figure.
  return at.map((p, i) => {
    const k = rank.get(i)!;
    const human = k < HUMAN;
    return { ...p, human, red: k < RED, n: human ? h++ : b++, angle: (next() - 0.5) * 150, phase: next() * Math.PI * 2 };
  });
})();

const NEUTRAL = "#c9d6d2";
const BLUE = "#5db4ff";
const GREEN = "#a6e05a";
const BLOOD = "#e8474c";

// How long each bacterium waits before leaving for the scale, set so that the last one lands as
// the weight is spoken rather than at a fixed speed.
const FLIGHT = 18;
const leaveAt = (n: number) => F.scale + (n * Math.max(0, F.two - F.scale - FLIGHT)) / (BACTERIA - 1);

const Cell: React.FC<{ d: Dot; f: number }> = ({ d, f }) => {
  const appear = ramp(f, d.y / 60, d.y / 60 + 8);

  let x = d.x;
  let y = d.y;
  let r = R;
  let color: string;
  let squash = 1;
  let rotate = 0;
  let opacity = 1;
  let dimple = 0;

  if (d.human) {
    color = interpolateColors(f, [F.thirty + d.n * 0.7, F.thirty + d.n * 0.7 + 8], [NEUTRAL, BLUE]);
    // "Your own cells": the ones still standing step forward before most of them turn out to be blood.
    r *= 1 + 0.16 * Math.sin(Math.PI * ramp(f, F.own + d.n * 0.3, F.own + d.n * 0.3 + 12));
    if (d.red) {
      // Spread across the sentence, so the last one turns as "red blood cells" finishes.
      const s = F.eightyFour + (d.n * (F.red - F.eightyFour + 8)) / HUMAN;
      dimple = ramp(f, s, s + 8);
      color = interpolateColors(f, [s, s + 8], [color, BLOOD]);
      // "Mostly blood": the 25 swell together, which leaves the five that are not standing out.
      r *= 1 + 0.2 * Math.sin(Math.PI * ramp(f, F.mostly + d.n * 0.4, F.mostly + d.n * 0.4 + 14));
    }
  } else {
    // "Less than half human": the other 38 fall back before anyone says what they are.
    opacity = 1 - 0.55 * ramp(f, F.less, F.half + 4) * (1 - ramp(f, F.thirtyEight + d.n * 0.5, F.thirtyEight + d.n * 0.5 + 8));
    const morph = ramp(f, F.thirtyEight + d.n * 0.5, F.thirtyEight + d.n * 0.5 + 8);
    color = interpolateColors(morph, [0, 1], [NEUTRAL, GREEN]);
    // Rods rather than discs, so the two populations differ by shape and not by colour alone.
    squash = 1 - 0.42 * morph;
    rotate = d.angle * morph;

    // Out to the scale and, on the last line, back. They shrink on the way because that is the
    // whole reason 38 trillion of them weigh 200 g: a bacterium is far smaller than a human cell.
    const go = smooth(ramp(f, leaveAt(d.n), leaveAt(d.n) + FLIGHT));
    const back = smooth(ramp(f, F.outnumbered + d.n * 0.5, F.outnumbered + d.n * 0.5 + 16));
    const p = go - back;
    const pile = PILE[d.n];
    x += (pile.x - x) * p;
    y += (pile.y - y) * p - Math.sin(Math.PI * p) * 110;
    r += (SMALL - r) * p;
    rotate *= 1 - p;
  }

  // Cells on a slide are never quite still; scaled by size so the mound does not shimmer.
  const drift = (r / R) * 2.6;
  x += Math.sin(f * 0.05 + d.phase) * drift;
  y += Math.cos(f * 0.043 + d.phase * 1.7) * drift;

  return (
    <div
      style={{
        position: "absolute",
        left: x - r,
        top: y - r * squash,
        width: r * 2,
        height: r * 2 * squash,
        borderRadius: r,
        background: color,
        opacity: opacity * appear,
        scale: `${0.4 + 0.6 * appear}`,
        rotate: `${rotate}deg`,
        boxShadow: `inset ${-r * 0.18}px ${-r * 0.22}px ${r * 0.5}px rgba(0,0,0,0.28)`,
      }}
    >
      {/* A red blood cell is a disc with a dent in it, which is the one thing everyone knows about its shape. */}
      {dimple > 0 ? (
        <div style={{ position: "absolute", inset: "24%", borderRadius: "50%", background: "radial-gradient(circle, rgba(110,10,20,0.75) 0%, rgba(110,10,20,0) 78%)", opacity: dimple }} />
      ) : null}
    </div>
  );
};

// A kitchen scale, because the number on it is a kitchen number.
const Scale: React.FC<{ opacity: number; grams: number }> = ({ opacity, grams }) => (
  <div style={{ position: "absolute", left: PAN.x, top: PAN.y, opacity }}>
    <div style={{ position: "absolute", left: -PAN.w / 2, top: 0, width: PAN.w, height: 12, borderRadius: 6, background: "#b9c9c5" }} />
    <div style={{ position: "absolute", left: -22, top: 12, width: 44, height: 16, background: "#6f807c" }} />
    <div
      style={{
        position: "absolute",
        left: -150,
        top: 28,
        width: 300,
        height: 150,
        borderRadius: 22,
        background: "linear-gradient(#34494a, #1c2b2d)",
        border: "3px solid #57706d",
        boxSizing: "border-box",
        display: "flex",
        flexDirection: "column",
        alignItems: "center",
        justifyContent: "center",
      }}
    >
      <div style={{ font: `700 66px ${SANS}`, color: "#d8ff9a", letterSpacing: 2, lineHeight: 1 }}>{grams} g</div>
      <div style={{ fontFamily: SERIF, fontSize: 28, color: "#b7c9c2", marginTop: 8 }}>in a 70 kg body</div>
    </div>
  </div>
);

const CellScene: React.FC = () => {
  const f = useCurrentFrame();
  const landed = DOTS.filter((d) => !d.human && f >= leaveAt(d.n) + FLIGHT).length;
  const scale = ramp(f, F.scale - 8, F.scale + 4) - ramp(f, F.outnumbered - 6, F.outnumbered + 6);

  return (
    <>
      {scale > 0 ? <Scale opacity={scale} grams={Math.round((200 * landed) / BACTERIA)} /> : null}
      {DOTS.map((d, i) => (
        <Cell key={i} d={d} f={f} />
      ))}

      {/* One column, right of the figure: the 9:16 crop has nowhere else, and a label that stays
          put is one the eye does not have to find again. */}
      <Tag x={COLUMN} y={130} text="44% HUMAN" sub="by cell count" from={F.half} to={F.thirty - 4} />
      <Tag x={COLUMN} y={130} text="30 TRILLION" sub="your own cells" from={F.thirty + 6} to={F.scale - 6} />
      <Tag x={COLUMN} y={280} text="38 TRILLION" sub="bacteria" from={F.thirtyEight + 6} to={F.scale - 6} />
      <Tag x={COLUMN} y={130} text={"38 TRILLION\nBACTERIA"} sub="each one far smaller" from={F.scale + 8} to={F.own - 6} />
      <Tag x={COLUMN} y={130} text={"YOUR 30\nTRILLION"} sub="counted, not weighed" from={F.own + 4} to={F.eightyFour - 4} />
      <Tag x={COLUMN} y={130} text={"84% RED\nBLOOD CELLS"} sub="25 of your 30 trillion" from={F.eightyFour + 6} to={F.outnumbered - 6} />
      {/* The two populations side by side on the last line, stacked because the column is narrow. */}
      <Tag x={COLUMN} y={130} text="30 TRILLION" sub="yours, mostly blood" from={F.outnumbered + 6} />
      <Tag x={COLUMN} y={280} text="38 TRILLION" sub="passengers" from={F.passengers - 4} />
    </>
  );
};

export const cellCount: Short = {
  slug: "cell-count",
  title: "You are less than half human",
  edit,
  looks: [{ id: "Lab", Set: Slide, cast: () => [] }],
  props: () => <CellScene />,
  sfx: [
    { at: F.thirty, name: "pop", volume: 0.35 },
    { at: F.thirtyEight, name: "pop", volume: 0.35 },
    { at: F.scale, name: "whoosh", volume: 0.35 },
    { at: F.two, name: "thud", volume: 0.5 },
    { at: F.outnumbered, name: "whoosh", volume: 0.35 },
  ],
};
